// Open Board Format export (https://www.openboardformat.org). Single-board .obf JSON.

import type { Board, Lang } from "./types";
import { pick } from "./vocab";

export interface ObfBoard {
  format: "open-board-0.1";
  id: string;
  locale: string;
  name: string;
  description_html: string;
  buttons: {
    id: string;
    label: string;
    vocalization: string;
    image_id?: string;
    background_color?: string;
    ext_hometiles_category: string;
    ext_hometiles_reason?: string;
  }[];
  grid: { rows: number; columns: number; order: (string | null)[][] };
  images: { id: string; url: string; content_type: string; width: number; height: number }[];
  license: { type: string; author_name: string; author_url: string };
}

const COLORS: Record<string, string> = {
  core: "rgb(255, 241, 179)",
  safety: "rgb(255, 205, 205)",
  people: "rgb(214, 234, 255)",
  food: "rgb(255, 224, 194)",
  places: "rgb(209, 240, 214)",
  favourites: "rgb(233, 220, 255)",
  fun: "rgb(255, 214, 236)",
  together: "rgb(204, 238, 238)",
  new: "rgb(238, 238, 238)",
};

// OBF locales are plain language codes, the same as ours.
const LOCALE = (l: Lang): string => l;

export function toObf(board: Board, lang: Lang, columns = 6): ObfBoard {
  const ids = [...board.coreIds, ...board.folders.flatMap((f) => f.tileIds)];
  const unique = [...new Set(ids)].filter((id) => board.tiles[id]);
  const buttons: ObfBoard["buttons"] = [];
  const images: ObfBoard["images"] = [];
  unique.forEach((id, i) => {
    const t = board.tiles[id];
    const bid = String(i + 1);
    let image_id: string | undefined;
    if (t.image?.url) {
      image_id = `img${i + 1}`;
      images.push({ id: image_id, url: t.image.url, content_type: "image/png", width: 300, height: 300 });
    }
    buttons.push({
      id: bid,
      label: pick(t.label, lang),
      vocalization: pick(t.label, lang), // same as Cboard: a tile says its label
      image_id,
      background_color: COLORS[t.category],
      ext_hometiles_category: t.category,
      ext_hometiles_reason: t.reasons[0]?.text,
    });
  });
  const rows = Math.ceil(buttons.length / columns);
  const order: (string | null)[][] = [];
  for (let r = 0; r < rows; r++) {
    order.push(Array.from({ length: columns }, (_, c) => buttons[r * columns + c]?.id ?? null));
  }
  return {
    format: "open-board-0.1",
    id: board.id,
    locale: LOCALE(lang),
    name: `${board.profile.displayName}'s HomeTiles board`,
    description_html: "Generated by HomeTiles from the person's own culture, neighbourhood and favourite things.",
    buttons,
    grid: { rows, columns, order },
    images,
    license: { type: "CC-By", author_name: "HomeTiles", author_url: "https://github.com/" },
  };
}
